import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const contractsPath = path.resolve(__dirname, '../../contracts/openapi.json');
const currentGeneratedPath = path.resolve(__dirname, '../src/api/generated.ts');

if (!fs.existsSync(contractsPath)) {
  console.error(`Error: contracts/openapi.json not found at ${contractsPath}`);
  process.exit(1);
}

if (!fs.existsSync(currentGeneratedPath)) {
  console.error(`Error: generated.ts not found at ${currentGeneratedPath}`);
  process.exit(1);
}

async function checkDrift() {
  const schema = JSON.parse(fs.readFileSync(contractsPath, 'utf8'));
  const ast = await openapiTS(schema);
  const rawGenerated = astToString(ast);
  const header = `/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n`;
  const generated = header + rawGenerated;
  const current = fs.readFileSync(currentGeneratedPath, 'utf8');

  const normGenerated = generated.replace(/\r\n/g, '\n').trim();
  const normCurrent = current.replace(/\r\n/g, '\n').trim();

  if (normGenerated !== normCurrent) {
    console.error(
      'API drift detected! The types in frontend/src/api/generated.ts do not match contracts/openapi.json.'
    );
    console.error('Run `npm run api:generate` in the frontend directory to update.');
    process.exit(1);
  }

  console.log('API schema and generated TypeScript types are in sync.');
}

checkDrift().catch((err) => {
  console.error('Failed to check API drift:', err);
  process.exit(1);
});
